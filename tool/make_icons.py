"""Draws FITNS's launcher and store icons from one set of shapes.

A white dumbbell, tilted, on FITNS orange. Writes:
  - the adaptive icon (Android 8+): vector foreground + orange background,
    plus a monochrome layer for Android 13's themed icons
  - legacy PNG launcher icons for Android 7 (mipmap-*dpi)
  - a 512 px store icon for Google Play and F-Droid

Run from the repo root after changing a shape or colour:
    python tool/make_icons.py
Needs Pillow (pip install pillow).
"""

from pathlib import Path

from PIL import Image, ImageDraw

ORANGE = "#EA580C"
WHITE = "#FFFFFF"

# Adaptive icons are 108 dp with the visible mask inside the middle 66 dp;
# everything below stays within 28..80, well inside it.
VIEWPORT = 108
TILT = -45  # degrees, about the centre

# (left, top, right, bottom, corner radius) in the 108 dp viewport, before tilt.
SHAPES = [
    (25, 43, 32, 65, 2.5),  # left outer plate
    (32, 35, 41, 73, 3),  # left inner plate
    (40, 50.5, 68, 57.5, 2),  # bar
    (67, 35, 76, 73, 3),  # right inner plate
    (76, 43, 83, 65, 2.5),  # right outer plate
]

RES = Path("android/app/src/main/res")
STORE_ICON = Path("fastlane/metadata/android/en-US/images/icon.png")
LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def _rrect_path(l, t, r, b, rad):
    return (
        f"M{l + rad},{t} H{r - rad} A{rad},{rad} 0 0 1 {r},{t + rad} "
        f"V{b - rad} A{rad},{rad} 0 0 1 {r - rad},{b} H{l + rad} "
        f"A{rad},{rad} 0 0 1 {l},{b - rad} V{t + rad} "
        f"A{rad},{rad} 0 0 1 {l + rad},{t} Z"
    )


def _vector(fill):
    paths = "\n".join(
        f'        <path android:fillColor="{fill}" '
        f'android:pathData="{_rrect_path(*s)}"/>'
        for s in SHAPES
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py - edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="{VIEWPORT}"
    android:viewportHeight="{VIEWPORT}">
    <group
        android:pivotX="{VIEWPORT / 2}"
        android:pivotY="{VIEWPORT / 2}"
        android:rotation="{TILT}">
{paths}
    </group>
</vector>
"""


def _render(size, *, inset_to_mask, rounded):
    """The icon as a PNG: orange square (optionally rounded) + dumbbell."""
    scale = 8  # draw big, shrink down: cheap anti-aliasing
    big = size * scale
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    if rounded:
        draw.rounded_rectangle((0, 0, big - 1, big - 1), radius=big * 0.22, fill=ORANGE)
    else:
        draw.rectangle((0, 0, big, big), fill=ORANGE)

    # Cropping to the 72 dp middle (as a launcher's mask does) leaves the
    # mark crowding the edges of a flat PNG; the full canvas gives it room.
    visible = 72 if inset_to_mask else VIEWPORT
    offset = (VIEWPORT - visible) / 2
    unit = big / visible

    mark = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    mdraw = ImageDraw.Draw(mark)
    for l, t, r, b, rad in SHAPES:
        mdraw.rounded_rectangle(
            ((l - offset) * unit, (t - offset) * unit, (r - offset) * unit, (b - offset) * unit),
            radius=rad * unit,
            fill=WHITE,
        )
    # PIL rotates counter-clockwise for positive angles; Android clockwise.
    mark = mark.rotate(-TILT, resample=Image.BICUBIC, center=(big / 2, big / 2))
    img.alpha_composite(mark)
    return img.resize((size, size), Image.LANCZOS)


def main():
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(_vector(WHITE), newline="\n")
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py - edit that, not this. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
"""
    (anydpi / "ic_launcher.xml").write_text(adaptive, newline="\n")
    (RES / "values" / "ic_launcher_background.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py - edit that, not this. -->
<resources>
    <color name="ic_launcher_background">{ORANGE}</color>
</resources>
""",
        newline="\n",
    )
    for density, size in LEGACY_SIZES.items():
        _render(size, inset_to_mask=False, rounded=True).save(
            RES / f"mipmap-{density}" / "ic_launcher.png", optimize=True
        )
    STORE_ICON.parent.mkdir(parents=True, exist_ok=True)
    # Play masks the store icon itself, so it goes up square.
    _render(512, inset_to_mask=False, rounded=False).save(STORE_ICON, optimize=True)
    print("Icons written.")


if __name__ == "__main__":
    main()

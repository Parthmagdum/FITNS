"""Draws FITNS's launcher and store icons from one set of shapes.

The FITNS mark: a forward-leaning "F" whose top bar reaches up and ahead,
with a dot above it — an F that is also a figure in stride. White on FITNS
orange. Writes:
  - the adaptive icon (Android 8+): vector foreground + orange background,
    plus a monochrome layer for Android 13's themed icons
  - legacy PNG launcher icons for Android 7 (mipmap-*dpi)
  - a 512 px store icon for Google Play and F-Droid
  - the 1024 x 500 store feature graphic

The same shapes are drawn in the app by lib/core/branding/fitns_logo.dart
and, for the widgets, android/.../res/drawable/ic_w_logo.xml (written here
too) — keep them in step.

Run from the repo root after changing a shape or colour:
    python tool/make_icons.py
Needs Pillow (pip install pillow).
"""

import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ORANGE = "#EA580C"
ORANGE_DARK = "#C2410C"
WHITE = "#FFFFFF"

# Adaptive icons are 108 dp; the smallest mask is a circle of radius 36
# about the centre. Every shape stays within 34 of it (checked in main).
VIEWPORT = 108

# The mark, in the 108 dp viewport: three round-capped strokes and a dot.
STROKE = 9.9
STROKES = [
    ((46.8, 80.1), (55.0, 41.4)),  # the stem, leaning forward
    ((55.0, 41.4), (73.9, 37.1)),  # the top bar, reaching up and ahead
    ((51.0, 60.4), (66.2, 57.8)),  # the middle bar
]
DOT = ((59.0, 26.5), 5.5)  # centre, radius: the head, clear of the bar

RES = Path("android/app/src/main/res")
STORE_ICON = Path("fastlane/metadata/android/en-US/images/icon.png")
FEATURE = Path("fastlane/metadata/android/en-US/images/featureGraphic.png")
FONT = Path("assets/fonts/Inter-Variable.ttf")
LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def _check_safe_zone():
    c = VIEWPORT / 2
    for a, b in STROKES:
        for x, y in (a, b):
            assert math.hypot(x - c, y - c) + STROKE / 2 <= 34, (x, y)
    (x, y), r = DOT
    assert math.hypot(x - c, y - c) + r <= 34, "dot"


def _vector(colour):
    lines = "\n".join(
        f'    <path android:strokeColor="{colour}" android:strokeWidth="{STROKE}" '
        f'android:strokeLineCap="round" '
        f'android:pathData="M{a[0]},{a[1]} L{b[0]},{b[1]}"/>'
        for a, b in STROKES
    )
    (x, y), r = DOT
    dot = (
        f'    <path android:fillColor="{colour}" android:pathData="'
        f"M{x - r},{y} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 Z\"/>"
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py - edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="{VIEWPORT}"
    android:viewportHeight="{VIEWPORT}">
{lines}
{dot}
</vector>
"""


def _mark(size, *, visible=VIEWPORT, colour=WHITE):
    """The mark alone, on transparent, [size] px, showing the middle
    [visible] dp of the viewport."""
    scale = 8  # draw big, shrink down: cheap anti-aliasing
    big = size * scale
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    offset = (VIEWPORT - visible) / 2
    unit = big / visible

    def p(x, y):
        return ((x - offset) * unit, (y - offset) * unit)

    w = STROKE * unit
    for a, b in STROKES:
        draw.line([p(*a), p(*b)], fill=colour, width=round(w))
        for x, y in (a, b):
            cx, cy = p(x, y)
            draw.ellipse((cx - w / 2, cy - w / 2, cx + w / 2, cy + w / 2), fill=colour)
    (x, y), r = DOT
    cx, cy = p(x, y)
    draw.ellipse((cx - r * unit, cy - r * unit, cx + r * unit, cy + r * unit), fill=colour)
    return img.resize((size, size), Image.LANCZOS)


def _render(size, *, rounded):
    """The icon as a PNG: orange square (optionally rounded) + the mark."""
    scale = 8
    big = size * scale
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    if rounded:
        draw.rounded_rectangle((0, 0, big - 1, big - 1), radius=big * 0.22, fill=ORANGE)
    else:
        draw.rectangle((0, 0, big, big), fill=ORANGE)
    img = img.resize((size, size), Image.LANCZOS)
    # A flat PNG isn't masked: show a little more than the safe zone so the
    # mark has room.
    img.alpha_composite(_mark(size, visible=84))
    return img


def _hex(c):
    c = c.lstrip("#")
    return tuple(int(c[i : i + 2], 16) for i in (0, 2, 4))


def _feature_graphic():
    w, h = 1024, 500
    img = Image.new("RGBA", (w, h))
    a, b = _hex(ORANGE), _hex(ORANGE_DARK)
    draw = ImageDraw.Draw(img)
    for x in range(w):
        t = x / (w - 1)
        draw.line([(x, 0), (x, h)], fill=tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3)))
    img.alpha_composite(_mark(300, visible=72), (70, 100))
    title = ImageFont.truetype(str(FONT), 150)
    title.set_variation_by_axes([32, 800])
    tag = ImageFont.truetype(str(FONT), 40)
    tag.set_variation_by_axes([20, 500])
    draw.text((420, 245), "FITNS", font=title, fill=WHITE, anchor="ls")
    draw.text((426, 320), "Fitness, tracked offline.", font=tag, fill=(255, 255, 255, 235), anchor="ls")
    img.convert("RGB").save(FEATURE, optimize=True)


def main():
    _check_safe_zone()
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    # Always UTF-8: Windows' default codepage would make aapt reject the XML.
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(
        _vector(WHITE), newline="\n", encoding="utf-8"
    )
    # The same mark for the home-screen widgets' badge.
    (RES / "drawable" / "ic_w_logo.xml").write_text(
        _vector(WHITE), newline="\n", encoding="utf-8"
    )
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py - edit that, not this. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
"""
    (anydpi / "ic_launcher.xml").write_text(adaptive, newline="\n", encoding="utf-8")
    (RES / "values" / "ic_launcher_background.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py - edit that, not this. -->
<resources>
    <color name="ic_launcher_background">{ORANGE}</color>
</resources>
""",
        newline="\n",
        encoding="utf-8",
    )
    for density, size in LEGACY_SIZES.items():
        _render(size, rounded=True).save(RES / f"mipmap-{density}" / "ic_launcher.png", optimize=True)
    STORE_ICON.parent.mkdir(parents=True, exist_ok=True)
    # Play masks the store icon itself, so it goes up square.
    _render(512, rounded=False).save(STORE_ICON, optimize=True)
    _feature_graphic()
    print("Icons written.")


if __name__ == "__main__":
    main()
